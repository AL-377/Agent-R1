"""
Examiner Agent preprocessing script.

Convert the raw carecall cache format (with oracle_memory_base/to_memory)
into the target format by attaching memory_query generated by an examiner agent.
"""

import json
import os
import random
import re
import concurrent.futures
from typing import Any, Dict, List, Optional, Tuple
from tqdm import tqdm

from agent_r1.utils.llm import query_llm_inhouse

DEFAULT_MODEL = "gpt-4o-2024-11-20"


def _strip_think_and_fence(text: str) -> str:
    text = text.strip()
    if text.startswith("<think>"):
        think_end = text.find("</think>")
        if think_end != -1:
            text = text[think_end + len("</think>"):].strip()
    text = re.sub(r"```json\s*", "", text)
    text = re.sub(r"```\s*", "", text)
    return text.strip()


def _safe_json_load(text: str) -> Optional[Dict[str, Any]]:
    text = _strip_think_and_fence(text)
    if text.startswith("{"):
        try:
            return json.loads(text)
        except Exception:
            return None
    return None


def _flatten_memory_items(oracle_memory_base: Dict[str, Any]) -> List[Dict[str, Any]]:
    items: List[Dict[str, Any]] = []
    for layer, layer_items in oracle_memory_base.items():
        for item in layer_items or []:
            if isinstance(item, dict) and "id" in item and "content" in item:
                items.append(
                    {
                        "id": item.get("id"),
                        "content": item.get("content"),
                        "layer": layer,
                        "timestamp": item.get("timestamp"),
                        "metadata": item.get("metadata") or {},
                    }
                )
    return items


def _parse_to_memory_layers(to_memory: List[Any]) -> List[str]:
    layers = []
    for item in to_memory or []:
        if not item:
            continue
        item_str = str(item).strip()
        if ":" in item_str:
            layer = item_str.split(":", 1)[0].strip()
            if layer in ["working", "identity", "history", "experience"]:
                layers.append(layer)
    return layers


def _group_source_by_layer(items: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    layer_map: Dict[str, List[str]] = {}
    for item in items:
        layer = item.get("layer")
        memory_id = item.get("id")
        if layer and memory_id:
            layer_map.setdefault(layer, []).append(memory_id)
    return [{"layer": layer, "ids": ids} for layer, ids in layer_map.items()]


def _detect_language_hint(text: str) -> str:
    # Simple heuristic: if there are CJK chars, use Chinese; otherwise English.
    for ch in text:
        if "\u4e00" <= ch <= "\u9fff":
            return "zh"
    return "en"


def _select_memory_items(
    oracle_memory_base: Dict[str, Any],
    to_memory: List[Any],
    rng: random.Random,
    conflict_prob: float = 0.1,
) -> Optional[Tuple[str, str, List[Dict[str, Any]]]]:
    layers = {
        "working": oracle_memory_base.get("working", []) or [],
        "identity": oracle_memory_base.get("identity", []) or [],
        "history": oracle_memory_base.get("history", []) or [],
        "experience": oracle_memory_base.get("experience", []) or [],
    }
    has_working = len(layers["working"]) > 0
    has_identity = len(layers["identity"]) > 0
    has_history = len(layers["history"]) > 0
    has_experience = len(layers["experience"]) > 0

    if not (has_working or has_identity or has_history or has_experience):
        return None

    to_memory_layers = set(_parse_to_memory_layers(to_memory))

    # Candidate pools
    working_items = _flatten_memory_items({"working": layers["working"]})
    identity_items = _flatten_memory_items({"identity": layers["identity"]})
    history_items = _flatten_memory_items({"history": layers["history"]})
    experience_items = _flatten_memory_items({"experience": layers["experience"]})

    # Level 4: conflict check (cross-layer)
    if (has_working and (has_history or has_identity)) and rng.random() < conflict_prob:
        base_layer_items = history_items if has_history else identity_items
        selected = [rng.choice(base_layer_items), rng.choice(working_items)]
        return ("Level 4", "Conflict & Safety Check", selected)

    # Level 3: long-range (history + working)
    if has_working and has_history and rng.random() < 0.4:
        selected = [rng.choice(history_items), rng.choice(working_items)]
        return ("Level 3", "Long-range Understanding", selected)

    # Level 2: factual retrieval from identity/history/experience
    if (has_identity or has_history or has_experience) and rng.random() < 0.6:
        pool = identity_items + history_items + experience_items
        selected = [rng.choice(pool)]
        return ("Level 2", "Accurate Retrieval", selected)

    # Level 1: working-only (state tracking)
    if has_working:
        selected = [rng.choice(working_items)]
        return ("Level 1", "State Tracking", selected)

    # Fallback to Level 2 if no working items
    pool = identity_items + history_items + experience_items
    if pool:
        selected = [rng.choice(pool)]
        return ("Level 2", "Accurate Retrieval", selected)

    return None


def _build_examiner_prompt(
    current_turn: str,
    selected_items: List[Dict[str, Any]],
    difficulty: str,
    query_type: str,
    language_hint: str,
) -> str:
    def _level_guidance(lang: str, level: str, qtype: str) -> str:
        if lang == "zh":
            if level == "Level 1":
                return (
                    "【Level 1 指南】仅基于当前对话(working)的直接事实检索或状态追踪。\n"
                    "示例问题: \"患者刚才提到的主要不适是什么？\"\n"
                    "示例答案: \"患者主诉头痛并伴随恶心。\""
                )
            if level == "Level 2":
                return (
                    "【Level 2 指南】从 identity/history/experience 中检索长期记忆事实，不引入新推理。\n"
                    "示例问题: \"患者的职业是什么？\"\n"
                    "示例答案: \"患者是卡车司机。\""
                )
            if level == "Level 3":
                return (
                    "【Level 3 指南】结合 history 与 working，要求对比或关联新旧信息。\n"
                    "示例问题: \"结合既往病史，患者当前口渴多尿提示与哪种疾病相关？\"\n"
                    "示例答案: \"与既往2型糖尿病史相关。\""
                )
            return (
                "【Level 4 指南】跨层冲突/安全检查，关注矛盾或禁忌。\n"
                "示例问题: \"患者有青霉素过敏史，医生刚才开的药是否安全？\"\n"
                "示例答案: \"不安全，需避免青霉素类。\""
            )
        if level == "Level 1":
            return (
                "Level 1 Guidance: Only use working-memory facts from the current turn.\n"
                "Example Q: \"What symptom did the patient just report?\"\n"
                "Example A: \"The patient reported a headache with nausea.\""
            )
        if level == "Level 2":
            return (
                "Level 2 Guidance: Retrieve factual info from identity/history/experience only.\n"
                "Example Q: \"What is the patient's occupation?\"\n"
                "Example A: \"The patient is a truck driver.\""
            )
        if level == "Level 3":
            return (
                "Level 3 Guidance: Combine history + working; compare or relate new vs old info.\n"
                "Example Q: \"Given the history, what condition best explains the current thirst and polyuria?\"\n"
                "Example A: \"It aligns with the patient's type 2 diabetes history.\""
            )
        return (
            "Level 4 Guidance: Cross-layer conflict/safety check (contraindication or inconsistency).\n"
            "Example Q: \"With a penicillin allergy in history, is the newly prescribed drug safe?\"\n"
            "Example A: \"No, avoid penicillin-class drugs.\""
        )

    items_text = "\n".join(
        [
            f"- id: {item['id']}, layer: {item['layer']}, content: {item['content']}"
            for item in selected_items
        ]
    )
    if language_hint == "zh":
        return f"""你是一个医疗记忆评测专家。请根据【目标记忆点】生成一道问题和答案，用于测试医生助手是否记住这些信息。

【当前对话内容】:
{current_turn}

【目标记忆点】(请只基于这些内容出题):
{items_text}

{_level_guidance("zh", difficulty, query_type)}

要求:
1. 输出 JSON 对象，包含字段: difficulty, type, question, answer。
2. difficulty 固定为 "{difficulty}"，type 固定为 "{query_type}"。
3. 问题要具体、自然、简洁，不要包含 id。
4. 答案应基于目标记忆点，尽量简洁。

只输出 JSON 对象，不要输出其它内容。"""
    return f"""You are a medical memory evaluation expert. Generate a question and answer based on the target memory items to test whether the assistant remembers them.

Current turn:
{current_turn}

Target memory items (use only these):
{items_text}

{_level_guidance("en", difficulty, query_type)}

Requirements:
1. Output a JSON object with fields: difficulty, type, question, answer.
2. difficulty must be "{difficulty}", type must be "{query_type}".
3. The question should be specific, natural, concise, and must not include ids.
4. The answer should be based on the target items and concise.

Output only the JSON object."""


def _generate_memory_query(
    current_turn: str,
    oracle_memory_base: Dict[str, Any],
    to_memory: List[Any],
    model_name: str,
    rng: random.Random,
    trigger_prob: float = 0.3,
) -> Optional[Dict[str, Any]]:
    # Trigger decision
    to_memory_clean = [item for item in (to_memory or []) if item]
    effective_prob = 0.7 if to_memory_clean else trigger_prob
    if rng.random() > effective_prob:
        return None

    selection = _select_memory_items(oracle_memory_base, to_memory, rng)
    if not selection:
        return None
    difficulty, query_type, selected_items = selection

    prompt = _build_examiner_prompt(
        current_turn=current_turn,
        selected_items=selected_items,
        difficulty=difficulty,
        query_type=query_type,
        language_hint=_detect_language_hint(current_turn),
    )

    response = query_llm_inhouse(
        model_name=model_name,
        messages=prompt,
        temperature=0.7,
        max_tokens=4096,
    )
    result_text = response.get("response", "")
    query_dict = _safe_json_load(result_text)
    if not query_dict:
        return None

    question = str(query_dict.get("question", "")).strip()
    answer = str(query_dict.get("answer", "")).strip()
    if not question or not answer:
        return None

    return {
        "difficulty": difficulty,
        "type": query_type,
        "question": question,
        "answer": answer,
        "source": _group_source_by_layer(selected_items),
    }


def _process_patient(
    patient_data: Dict[str, Any],
    model_name: str,
    rng: random.Random,
    trigger_prob: float,
) -> Dict[str, Any]:
    messages = []
    for msg in patient_data.get("messages", []):
        if msg == "---诊疗分割线---":
            messages.append(msg)
            continue

        if not isinstance(msg, dict) or not msg:
            messages.append(msg)
            continue

        role = list(msg.keys())[0]
        content = msg.get(role, {})
        if not isinstance(content, dict):
            messages.append(msg)
            continue

        if role == "user":
            memory_query = _generate_memory_query(
                current_turn=str(content.get("content", "")),
                oracle_memory_base=content.get("oracle_memory_base", {}),
                to_memory=content.get("to_memory", []),
                model_name=model_name,
                rng=rng,
                trigger_prob=trigger_prob,
            )
            if memory_query:
                content["memory_query"] = memory_query

        messages.append({role: content})

    return {
        "patient_id": patient_data.get("patient_id"),
        "messages": messages,
    }


def _load_input_data(input_file: str) -> List[Dict[str, Any]]:
    with open(input_file, "r", encoding="utf-8") as f:
        data = json.load(f)
    if isinstance(data, dict) and "messages" in data:
        return [data]
    if isinstance(data, list):
        return data
    raise ValueError("Unsupported input format.")


def _extract_patient_id_from_filename(filename: str) -> Optional[str]:
    """Extract patient ID from filename like 'patient_0.json'."""
    match = re.match(r"patient_(\d+)\.json$", filename)
    if match:
        return match.group(1)
    return None


def _scan_patient_files(input_dir: str) -> List[Tuple[str, str]]:
    """
    Scan directory for patient JSON files.
    
    Args:
        input_dir: Directory containing patient JSON files
        
    Returns:
        List of (patient_id, file_path) tuples
    """
    patient_files = []
    if not os.path.isdir(input_dir):
        raise ValueError(f"Input directory does not exist: {input_dir}")
    
    for filename in os.listdir(input_dir):
        if not filename.endswith(".json"):
            continue
        patient_id = _extract_patient_id_from_filename(filename)
        if patient_id is not None:
            file_path = os.path.join(input_dir, filename)
            patient_files.append((patient_id, file_path))
    
    # Sort by patient_id numerically
    def sort_key(item):
        try:
            return int(item[0])
        except ValueError:
            return item[0]
    
    patient_files.sort(key=sort_key)
    return patient_files


def save_patient_cache(patient_id: str, result: Dict, cache_dir: str) -> None:
    """
    Save processed patient data to cache file.
    
    Args:
        patient_id: Patient ID
        result: Processed patient data
        cache_dir: Cache directory path
    """
    if result is None:
        return
    
    os.makedirs(cache_dir, exist_ok=True)
    cache_file = os.path.join(cache_dir, f"patient_{patient_id}.json")
    try:
        # Use atomic write: write to temp file first, then rename
        temp_file = cache_file + ".tmp"
        with open(temp_file, 'w', encoding='utf-8') as f:
            json.dump(result, f, ensure_ascii=False, indent=2)
        os.replace(temp_file, cache_file)
    except Exception as e:
        print(f"Warning: Failed to save cache for patient {patient_id}: {e}")


def load_patient_cache(patient_id: str, cache_dir: str) -> Optional[Dict]:
    """
    Load processed patient data from cache file.
    
    Args:
        patient_id: Patient ID
        cache_dir: Cache directory path
    
    Returns:
        Cached patient data or None if not found
    """
    cache_file = os.path.join(cache_dir, f"patient_{patient_id}.json")
    if not os.path.exists(cache_file):
        return None
    
    try:
        with open(cache_file, 'r', encoding='utf-8') as f:
            return json.load(f)
    except Exception as e:
        print(f"Warning: Failed to load cache for patient {patient_id}: {e}")
        return None


def load_all_cached_patients(cache_dir: str) -> Dict[str, Dict]:
    """
    Load all cached patient data.
    
    Args:
        cache_dir: Cache directory path
    
    Returns:
        Dictionary mapping patient_id to cached data
    """
    cached_patients = {}
    if not os.path.exists(cache_dir):
        return cached_patients
    
    try:
        for filename in os.listdir(cache_dir):
            if filename.startswith("patient_") and filename.endswith(".json"):
                # Extract patient_id from filename
                patient_id = filename[8:-5]  # Remove "patient_" prefix and ".json" suffix
                cached_data = load_patient_cache(patient_id, cache_dir)
                if cached_data:
                    cached_patients[patient_id] = cached_data
    except Exception as e:
        print(f"Warning: Error loading cache directory: {e}")
    
    return cached_patients


def _process_single_patient(
    patient_id: str,
    input_file: str,
    model_name: str,
    seed: int,
    trigger_prob: float,
    cache_dir: Optional[str] = None,
) -> Optional[Dict[str, Any]]:
    """
    Process a single patient file.
    
    Args:
        patient_id: Patient ID
        input_file: Path to patient JSON file
        model_name: LLM model name
        seed: Random seed (will be offset by patient_id for determinism)
        trigger_prob: Trigger probability
        cache_dir: Optional cache directory
        
    Returns:
        Processed patient data or None if failed
    """
    try:
        # Load patient data
        with open(input_file, "r", encoding="utf-8") as f:
            patient_data = json.load(f)
        
        # Ensure patient_id is set
        if isinstance(patient_data, dict):
            patient_data["patient_id"] = patient_id
        
        # Create RNG with seed offset by patient_id for determinism
        rng = random.Random(seed + int(patient_id) if patient_id.isdigit() else seed)
        
        # Process patient
        result = _process_patient(patient_data, model_name, rng, trigger_prob)
        
        # Save to cache if cache_dir is provided
        if cache_dir and result:
            save_patient_cache(patient_id, result, cache_dir)
        
        return result
    except Exception as e:
        print(f"Error processing patient {patient_id}: {e}")
        return None


def process_dataset(
    input_file: Optional[str] = None,
    input_dir: Optional[str] = None,
    output_file: str = None,
    output_dir: Optional[str] = None,
    model_name: str = DEFAULT_MODEL,
    seed: int = 42,
    trigger_prob: float = 0.3,
    max_patients: Optional[int] = None,
    workers: int = 4,
    cache_dir: Optional[str] = None,
    use_cache: bool = True,
) -> None:
    """
    Process dataset in batch mode (directory) or single file mode.
    
    Args:
        input_file: Input JSON file (single file mode)
        input_dir: Input directory containing patient JSON files (batch mode)
        output_file: Output JSON file (single file mode or batch mode summary)
        output_dir: Output directory for individual patient files (batch mode)
        model_name: LLM model name
        seed: Random seed
        trigger_prob: Trigger probability
        max_patients: Maximum number of patients to process
        workers: Number of concurrent workers
        cache_dir: Cache directory path (auto-generated if None)
        use_cache: Whether to use cache
    """
    # Determine mode
    if input_dir:
        # Batch mode: process directory
        _process_dataset_batch(
            input_dir=input_dir,
            output_file=output_file,
            output_dir=output_dir,
            model_name=model_name,
            seed=seed,
            trigger_prob=trigger_prob,
            max_patients=max_patients,
            workers=workers,
            cache_dir=cache_dir,
            use_cache=use_cache,
        )
    elif input_file:
        # Single file mode: backward compatibility
        rng = random.Random(seed)
        data = _load_input_data(input_file)
        if max_patients:
            data = data[:max_patients]

        processed = []
        for patient in data:
            processed.append(_process_patient(patient, model_name, rng, trigger_prob))

        os.makedirs(os.path.dirname(output_file) if os.path.dirname(output_file) else '.', exist_ok=True)
        with open(output_file, "w", encoding="utf-8") as f:
            json.dump(processed, f, ensure_ascii=False, indent=2)
    else:
        raise ValueError("Either input_file or input_dir must be provided.")


def _process_dataset_batch(
    input_dir: str,
    output_file: Optional[str] = None,
    output_dir: Optional[str] = None,
    model_name: str = DEFAULT_MODEL,
    seed: int = 42,
    trigger_prob: float = 0.3,
    max_patients: Optional[int] = None,
    workers: int = 4,
    cache_dir: Optional[str] = None,
    use_cache: bool = True,
) -> None:
    """
    Process dataset in batch mode from directory.
    """
    # Setup cache directory
    if cache_dir is None and use_cache:
        if output_dir:
            cache_dir = os.path.join(output_dir, ".cache")
        elif output_file:
            base_name = os.path.splitext(os.path.basename(output_file))[0]
            cache_dir = os.path.join(os.path.dirname(output_file), f".{base_name}_cache")
        else:
            cache_dir = os.path.join(input_dir, ".examiner_cache")
    
    if use_cache:
        os.makedirs(cache_dir, exist_ok=True)
        print(f"Using cache directory: {cache_dir}")
    
    # Scan patient files
    print(f"Scanning patient files in {input_dir}...")
    patient_files = _scan_patient_files(input_dir)
    print(f"Found {len(patient_files)} patient files")
    
    if max_patients:
        patient_files = patient_files[:max_patients]
        print(f"Processing first {len(patient_files)} patients...")
    
    # Load cached patients
    cached_patients = {}
    if use_cache:
        print("Loading cached patients...")
        cached_patients = load_all_cached_patients(cache_dir)
        if cached_patients:
            print(f"Found {len(cached_patients)} cached patients")
    
    # Filter out already processed patients
    patients_to_process = []
    all_processed_data = []
    
    for patient_id, file_path in patient_files:
        if use_cache and patient_id in cached_patients:
            print(f"  Using cached data for patient {patient_id}")
            all_processed_data.append(cached_patients[patient_id])
        else:
            patients_to_process.append((patient_id, file_path))
    
    if not patients_to_process:
        print("All patients are already processed in cache!")
    else:
        print(f"Processing {len(patients_to_process)} new patients with {workers} workers...")
        
        # Process patients in parallel
        with concurrent.futures.ProcessPoolExecutor(max_workers=workers) as executor:
            # Submit tasks
            future_to_patient = {}
            for patient_id, file_path in patients_to_process:
                future = executor.submit(
                    _process_single_patient,
                    patient_id=patient_id,
                    input_file=file_path,
                    model_name=model_name,
                    seed=seed,
                    trigger_prob=trigger_prob,
                    cache_dir=cache_dir if use_cache else None,
                )
                future_to_patient[future] = patient_id
            
            # Process results as they complete
            for future in tqdm(concurrent.futures.as_completed(future_to_patient), total=len(patients_to_process)):
                patient_id = future_to_patient[future]
                try:
                    result = future.result()
                    if result:
                        all_processed_data.append(result)
                        # Save individual file if output_dir is specified
                        if output_dir:
                            os.makedirs(output_dir, exist_ok=True)
                            output_file_path = os.path.join(output_dir, f"patient_{patient_id}.json")
                            with open(output_file_path, 'w', encoding='utf-8') as f:
                                json.dump(result, f, ensure_ascii=False, indent=2)
                except Exception as e:
                    print(f"  Error processing patient {patient_id}: {e}")
    
    # Sort results by patient_id
    def sort_key(item):
        pid = item.get("patient_id", "")
        try:
            return int(pid)
        except ValueError:
            return pid
    
    all_processed_data.sort(key=sort_key)
    
    # Save summary file if output_file is specified
    if output_file:
        print(f"\nSaving processed data to {output_file}...")
        os.makedirs(os.path.dirname(output_file) if os.path.dirname(output_file) else '.', exist_ok=True)
        with open(output_file, 'w', encoding='utf-8') as f:
            json.dump(all_processed_data, f, ensure_ascii=False, indent=2)
    
    print(f"Done! Processed {len(all_processed_data)} patients total")
    if use_cache:
        print(f"Cache saved in: {cache_dir}")


def main():
    import argparse
    import multiprocessing

    # Set multiprocessing start method to 'spawn' for compatibility
    try:
        multiprocessing.set_start_method('spawn', force=True)
    except RuntimeError:
        # Start method may already be set, which is fine
        pass

    parser = argparse.ArgumentParser(
        description="Generate memory_query with Examiner Agent for carecall dataset."
    )
    parser.add_argument(
        "--input_file",
        type=str,
        default=None,
        help="Input JSON file (single file mode). Mutually exclusive with --input_dir.",
    )
    parser.add_argument(
        "--input_dir",
        type=str,
        default=None,
        help="Input directory containing patient JSON files (batch mode). Mutually exclusive with --input_file.",
    )
    parser.add_argument(
        "--output_file",
        type=str,
        default=None,
        help="Output JSON file (summary file in batch mode).",
    )
    parser.add_argument(
        "--output_dir",
        type=str,
        default=None,
        help="Output directory for individual patient files (batch mode).",
    )
    parser.add_argument(
        "--model_name",
        type=str,
        default=DEFAULT_MODEL,
        help="LLM model name.",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed.",
    )
    parser.add_argument(
        "--trigger_prob",
        type=float,
        default=0.3,
        help="Base probability to trigger a memory_query per user turn.",
    )
    parser.add_argument(
        "--max_patients",
        type=int,
        default=None,
        help="Optional max patients to process.",
    )
    parser.add_argument(
        "--workers",
        type=int,
        default=4,
        help="Number of concurrent workers (batch mode only).",
    )
    parser.add_argument(
        "--cache_dir",
        type=str,
        default=None,
        help="Cache directory path (auto-generated if not specified).",
    )
    parser.add_argument(
        "--no_cache",
        action="store_true",
        help="Disable cache (don't use or save cache).",
    )
    args = parser.parse_args()
    
    # Validate arguments
    if not args.input_file and not args.input_dir:
        parser.error("Either --input_file or --input_dir must be provided.")
    if args.input_file and args.input_dir:
        parser.error("--input_file and --input_dir are mutually exclusive.")
    if args.input_file and not args.output_file:
        parser.error("In single file mode (--input_file), --output_file must be provided.")
    if args.input_dir and not args.output_file and not args.output_dir:
        parser.error("In batch mode (--input_dir), either --output_file or --output_dir must be provided.")
    
    process_dataset(
        input_file=args.input_file,
        input_dir=args.input_dir,
        output_file=args.output_file,
        output_dir=args.output_dir,
        model_name=args.model_name,
        seed=args.seed,
        trigger_prob=args.trigger_prob,
        max_patients=args.max_patients,
        workers=args.workers,
        cache_dir=args.cache_dir,
        use_cache=not args.no_cache,
    )


if __name__ == "__main__":
    main()

