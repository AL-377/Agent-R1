"""
Examiner Agent preprocessing script.

Convert the raw carecall cache format (with oracle_memory_base/to_memory)
into the target format by attaching memory_query generated by an examiner agent.
"""

import json
import os
import random
import re
from typing import Any, Dict, List, Optional, Tuple

from agent_r1.utils.llm import query_llm_inhouse

DEFAULT_MODEL = "gpt-4o-2024-11-20"


def _strip_think_and_fence(text: str) -> str:
    text = text.strip()
    if text.startswith("<think>"):
        think_end = text.find("</think>")
        if think_end != -1:
            text = text[think_end + len("</think>"):].strip()
    text = re.sub(r"```json\s*", "", text)
    text = re.sub(r"```\s*", "", text)
    return text.strip()


def _safe_json_load(text: str) -> Optional[Dict[str, Any]]:
    text = _strip_think_and_fence(text)
    if text.startswith("{"):
        try:
            return json.loads(text)
        except Exception:
            return None
    return None


def _flatten_memory_items(oracle_memory_base: Dict[str, Any]) -> List[Dict[str, Any]]:
    items: List[Dict[str, Any]] = []
    for layer, layer_items in oracle_memory_base.items():
        for item in layer_items or []:
            if isinstance(item, dict) and "id" in item and "content" in item:
                items.append(
                    {
                        "id": item.get("id"),
                        "content": item.get("content"),
                        "layer": layer,
                        "timestamp": item.get("timestamp"),
                        "metadata": item.get("metadata") or {},
                    }
                )
    return items


def _parse_to_memory_layers(to_memory: List[Any]) -> List[str]:
    layers = []
    for item in to_memory or []:
        if not item:
            continue
        item_str = str(item).strip()
        if ":" in item_str:
            layer = item_str.split(":", 1)[0].strip()
            if layer in ["working", "identity", "history", "experience"]:
                layers.append(layer)
    return layers


def _group_source_by_layer(items: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    layer_map: Dict[str, List[str]] = {}
    for item in items:
        layer = item.get("layer")
        memory_id = item.get("id")
        if layer and memory_id:
            layer_map.setdefault(layer, []).append(memory_id)
    return [{"layer": layer, "ids": ids} for layer, ids in layer_map.items()]


def _detect_language_hint(text: str) -> str:
    # Simple heuristic: if there are CJK chars, use Chinese; otherwise English.
    for ch in text:
        if "\u4e00" <= ch <= "\u9fff":
            return "zh"
    return "en"


def _select_memory_items(
    oracle_memory_base: Dict[str, Any],
    to_memory: List[Any],
    rng: random.Random,
    conflict_prob: float = 0.1,
) -> Optional[Tuple[str, str, List[Dict[str, Any]]]]:
    layers = {
        "working": oracle_memory_base.get("working", []) or [],
        "identity": oracle_memory_base.get("identity", []) or [],
        "history": oracle_memory_base.get("history", []) or [],
        "experience": oracle_memory_base.get("experience", []) or [],
    }
    has_working = len(layers["working"]) > 0
    has_identity = len(layers["identity"]) > 0
    has_history = len(layers["history"]) > 0
    has_experience = len(layers["experience"]) > 0

    if not (has_working or has_identity or has_history or has_experience):
        return None

    to_memory_layers = set(_parse_to_memory_layers(to_memory))

    # Candidate pools
    working_items = _flatten_memory_items({"working": layers["working"]})
    identity_items = _flatten_memory_items({"identity": layers["identity"]})
    history_items = _flatten_memory_items({"history": layers["history"]})
    experience_items = _flatten_memory_items({"experience": layers["experience"]})

    # Level 4: conflict check (cross-layer)
    if (has_working and (has_history or has_identity)) and rng.random() < conflict_prob:
        base_layer_items = history_items if has_history else identity_items
        selected = [rng.choice(base_layer_items), rng.choice(working_items)]
        return ("Level 4", "Conflict & Safety Check", selected)

    # Level 3: long-range (history + working)
    if has_working and has_history and rng.random() < 0.4:
        selected = [rng.choice(history_items), rng.choice(working_items)]
        return ("Level 3", "Long-range Understanding", selected)

    # Level 2: factual retrieval from identity/history/experience
    if (has_identity or has_history or has_experience) and rng.random() < 0.6:
        pool = identity_items + history_items + experience_items
        selected = [rng.choice(pool)]
        return ("Level 2", "Accurate Retrieval", selected)

    # Level 1: working-only (state tracking)
    if has_working:
        selected = [rng.choice(working_items)]
        return ("Level 1", "State Tracking", selected)

    # Fallback to Level 2 if no working items
    pool = identity_items + history_items + experience_items
    if pool:
        selected = [rng.choice(pool)]
        return ("Level 2", "Accurate Retrieval", selected)

    return None


def _build_examiner_prompt(
    current_turn: str,
    selected_items: List[Dict[str, Any]],
    difficulty: str,
    query_type: str,
    language_hint: str,
) -> str:
    def _level_guidance(lang: str, level: str, qtype: str) -> str:
        if lang == "zh":
            if level == "Level 1":
                return (
                    "【Level 1 指南】仅基于当前对话(working)的直接事实检索或状态追踪。\n"
                    "示例问题: \"患者刚才提到的主要不适是什么？\"\n"
                    "示例答案: \"患者主诉头痛并伴随恶心。\""
                )
            if level == "Level 2":
                return (
                    "【Level 2 指南】从 identity/history/experience 中检索长期记忆事实，不引入新推理。\n"
                    "示例问题: \"患者的职业是什么？\"\n"
                    "示例答案: \"患者是卡车司机。\""
                )
            if level == "Level 3":
                return (
                    "【Level 3 指南】结合 history 与 working，要求对比或关联新旧信息。\n"
                    "示例问题: \"结合既往病史，患者当前口渴多尿提示与哪种疾病相关？\"\n"
                    "示例答案: \"与既往2型糖尿病史相关。\""
                )
            return (
                "【Level 4 指南】跨层冲突/安全检查，关注矛盾或禁忌。\n"
                "示例问题: \"患者有青霉素过敏史，医生刚才开的药是否安全？\"\n"
                "示例答案: \"不安全，需避免青霉素类。\""
            )
        if level == "Level 1":
            return (
                "Level 1 Guidance: Only use working-memory facts from the current turn.\n"
                "Example Q: \"What symptom did the patient just report?\"\n"
                "Example A: \"The patient reported a headache with nausea.\""
            )
        if level == "Level 2":
            return (
                "Level 2 Guidance: Retrieve factual info from identity/history/experience only.\n"
                "Example Q: \"What is the patient's occupation?\"\n"
                "Example A: \"The patient is a truck driver.\""
            )
        if level == "Level 3":
            return (
                "Level 3 Guidance: Combine history + working; compare or relate new vs old info.\n"
                "Example Q: \"Given the history, what condition best explains the current thirst and polyuria?\"\n"
                "Example A: \"It aligns with the patient's type 2 diabetes history.\""
            )
        return (
            "Level 4 Guidance: Cross-layer conflict/safety check (contraindication or inconsistency).\n"
            "Example Q: \"With a penicillin allergy in history, is the newly prescribed drug safe?\"\n"
            "Example A: \"No, avoid penicillin-class drugs.\""
        )

    items_text = "\n".join(
        [
            f"- id: {item['id']}, layer: {item['layer']}, content: {item['content']}"
            for item in selected_items
        ]
    )
    if language_hint == "zh":
        return f"""你是一个医疗记忆评测专家。请根据【目标记忆点】生成一道问题和答案，用于测试医生助手是否记住这些信息。

【当前对话内容】:
{current_turn}

【目标记忆点】(请只基于这些内容出题):
{items_text}

{_level_guidance("zh", difficulty, query_type)}

要求:
1. 输出 JSON 对象，包含字段: difficulty, type, question, answer。
2. difficulty 固定为 "{difficulty}"，type 固定为 "{query_type}"。
3. 问题要具体、自然、简洁，不要包含 id。
4. 答案应基于目标记忆点，尽量简洁。

只输出 JSON 对象，不要输出其它内容。"""
    return f"""You are a medical memory evaluation expert. Generate a question and answer based on the target memory items to test whether the assistant remembers them.

Current turn:
{current_turn}

Target memory items (use only these):
{items_text}

{_level_guidance("en", difficulty, query_type)}

Requirements:
1. Output a JSON object with fields: difficulty, type, question, answer.
2. difficulty must be "{difficulty}", type must be "{query_type}".
3. The question should be specific, natural, concise, and must not include ids.
4. The answer should be based on the target items and concise.

Output only the JSON object."""


def _generate_memory_query(
    current_turn: str,
    oracle_memory_base: Dict[str, Any],
    to_memory: List[Any],
    model_name: str,
    rng: random.Random,
    trigger_prob: float = 0.3,
) -> Optional[Dict[str, Any]]:
    # Trigger decision
    to_memory_clean = [item for item in (to_memory or []) if item]
    effective_prob = 0.7 if to_memory_clean else trigger_prob
    if rng.random() > effective_prob:
        return None

    selection = _select_memory_items(oracle_memory_base, to_memory, rng)
    if not selection:
        return None
    difficulty, query_type, selected_items = selection

    prompt = _build_examiner_prompt(
        current_turn=current_turn,
        selected_items=selected_items,
        difficulty=difficulty,
        query_type=query_type,
        language_hint=_detect_language_hint(current_turn),
    )

    response = query_llm_inhouse(
        model_name=model_name,
        messages=prompt,
        temperature=0.7,
        max_tokens=4096,
    )
    result_text = response.get("response", "")
    query_dict = _safe_json_load(result_text)
    if not query_dict:
        return None

    question = str(query_dict.get("question", "")).strip()
    answer = str(query_dict.get("answer", "")).strip()
    if not question or not answer:
        return None

    return {
        "difficulty": difficulty,
        "type": query_type,
        "question": question,
        "answer": answer,
        "source": _group_source_by_layer(selected_items),
    }


def _process_patient(
    patient_data: Dict[str, Any],
    model_name: str,
    rng: random.Random,
    trigger_prob: float,
) -> Dict[str, Any]:
    messages = []
    for msg in patient_data.get("messages", []):
        if msg == "---诊疗分割线---":
            messages.append(msg)
            continue

        if not isinstance(msg, dict) or not msg:
            messages.append(msg)
            continue

        role = list(msg.keys())[0]
        content = msg.get(role, {})
        if not isinstance(content, dict):
            messages.append(msg)
            continue

        if role == "user":
            memory_query = _generate_memory_query(
                current_turn=str(content.get("content", "")),
                oracle_memory_base=content.get("oracle_memory_base", {}),
                to_memory=content.get("to_memory", []),
                model_name=model_name,
                rng=rng,
                trigger_prob=trigger_prob,
            )
            if memory_query:
                content["memory_query"] = memory_query

        messages.append({role: content})

    return {
        "patient_id": patient_data.get("patient_id"),
        "messages": messages,
    }


def _load_input_data(input_file: str) -> List[Dict[str, Any]]:
    with open(input_file, "r", encoding="utf-8") as f:
        data = json.load(f)
    if isinstance(data, dict) and "messages" in data:
        return [data]
    if isinstance(data, list):
        return data
    raise ValueError("Unsupported input format.")


def process_dataset(
    input_file: str,
    output_file: str,
    model_name: str = DEFAULT_MODEL,
    seed: int = 42,
    trigger_prob: float = 0.3,
    max_patients: Optional[int] = None,
) -> None:
    rng = random.Random(seed)
    data = _load_input_data(input_file)
    if max_patients:
        data = data[:max_patients]

    processed = []
    for patient in data:
        processed.append(_process_patient(patient, model_name, rng, trigger_prob))

    os.makedirs(os.path.dirname(output_file), exist_ok=True)
    with open(output_file, "w", encoding="utf-8") as f:
        json.dump(processed, f, ensure_ascii=False, indent=2)


def main():
    import argparse

    parser = argparse.ArgumentParser(
        description="Generate memory_query with Examiner Agent for carecall dataset."
    )
    parser.add_argument(
        "--input_file",
        type=str,
        required=True,
        help="Input JSON file (raw carecall cache or list of patients).",
    )
    parser.add_argument(
        "--output_file",
        type=str,
        required=True,
        help="Output JSON file with memory_query added.",
    )
    parser.add_argument(
        "--model_name",
        type=str,
        default=DEFAULT_MODEL,
        help="LLM model name.",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed.",
    )
    parser.add_argument(
        "--trigger_prob",
        type=float,
        default=0.3,
        help="Base probability to trigger a memory_query per user turn.",
    )
    parser.add_argument(
        "--max_patients",
        type=int,
        default=None,
        help="Optional max patients to process.",
    )
    args = parser.parse_args()
    process_dataset(
        input_file=args.input_file,
        output_file=args.output_file,
        model_name=args.model_name,
        seed=args.seed,
        trigger_prob=args.trigger_prob,
        max_patients=args.max_patients,
    )


if __name__ == "__main__":
    main()

